"""public/assets/cmb/cmb.json: everything the scene and the legend need, plus provenance."""

from __future__ import annotations

import json
import math
import platform
from importlib import metadata
from pathlib import Path
from typing import Any

import colormap
import config


def _read_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        raise SystemExit(f"Missing {path}; run the earlier pipeline steps first")
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return data


def _uv_convention() -> dict[str, str]:
    return {
        "u": "u = (0.5 - l/360) mod 1, l in degrees; inverse l = (180 - 360u) mod 360. u = 0 and u = 1 are both l = 180.",
        "v": "v = 0.5 + b/180: v = 0 is the south galactic pole (b = -90), v = 1 the north galactic pole (b = +90).",
        "texelCentres": "u = (i + 0.5)/W, v = (k + 0.5)/H, where k counts stored rows from the first one.",
        "rowOrder": (
            "bottom-up: the first stored row of every mip level is the southernmost (b near -90). "
            "The KTX2 files carry KTXorientation 'ru' to say so."
        ),
        "loader": (
            "three's KTX2Loader keeps flipY = false (compressed textures cannot be flipped), so uv.y = 0 "
            "samples the first stored row, i.e. the south galactic pole. Use the texture as loaded; do not flip."
        ),
        "wrap": "wrapS = RepeatWrapping (longitude wraps at u = 0/1); wrapT = ClampToEdgeWrapping.",
    }


def _sphere_mapping() -> dict[str, str]:
    return {
        "directionToUv": (
            "For a unit direction in galactic Cartesian coordinates (x toward l = 0, b = 0; y toward l = 90, "
            "b = 0; z toward the north galactic pole): l = atan2(y, x) in degrees, b = asin(z), then u and v as above."
        ),
        "threeSphereGeometryTrue": (
            "three's SphereGeometry has uv.y = 1 at +y and uv.x running right-handed about +y from -x. Sampling "
            "the texture at (1 - uv.x, uv.y) maps the galactic frame by a proper rotation: Galactic centre "
            "(l = 0, b = 0) on +x, l = 90 on -z, north galactic pole on +y. Every point is in its true direction: "
            "from the centre (BackSide) it looks like the sky; from outside it is that sphere seen from beyond, "
            "the mirror image of the published map."
        ),
        "threeSphereGeometryAsPublished": (
            "Sampling at (uv.x, uv.y) unchanged shows, from outside, the map as published (l increasing to the "
            "left); this is a reflection of the true geometry."
        ),
        "facingCamera": "In both cases rotation.y = -PI/2 turns the Galactic centre toward a camera on +z.",
    }


def _software() -> dict[str, str]:
    versions = {"python": platform.python_version()}
    for package in ("healpy", "astropy", "numpy", "pillow"):
        versions[package] = metadata.version(package)
    return versions


def build_manifest() -> dict[str, Any]:
    stats = _read_json(config.GRID_STATS_PATH)
    encoded = _read_json(config.ENCODE_REPORT_PATH)
    preview_report_path = config.PREVIEW_DIR / "report.json"
    previews = _read_json(preview_report_path) if preview_report_path.exists() else {}

    table = colormap.load_table()
    stops = colormap.legend_stops(table, config.LEGEND_SUBDIVISIONS)
    source = stats["source"]
    native = source.get("native_beam_fwhm_arcmin")
    low, high = config.RANGE_MICROKELVIN

    return {
        "$comment": "Generated by scripts/preprocess-cmb.sh (scripts/cmb). Do not edit by hand.",
        "width": config.WIDTH,
        "height": config.HEIGHT,
        "files": dict(config.OUTPUT_FILES),
        "projection": "equirectangular",
        "frame": "galactic",
        "uAtLon0": 0.5,
        "lonIncreases": "left",
        "uv": _uv_convention(),
        "sphere": _sphere_mapping(),
        "column": source["column"],
        "unit": "uK_CMB",
        "range": [round(low), round(high)],
        "rangeSource": config.RANGE_SOURCE,
        "outOfRange": (
            f"clamped to the end colours ({100 * stats['grid']['fractionOutsideRange']:.2f}% of texels; "
            f"texel values span {stats['grid']['minUk']:.0f} to {stats['grid']['maxUk']:.0f} uK)"
        ),
        "colormap": {
            "name": "planck",
            "table": "Planck Parchment (colombi1)",
            "stops": [[position, colour] for position, colour in stops],
            "interpolation": (
                "linear between stops in sRGB-encoded values (the CSS linear-gradient default); "
                f"position 0 = {round(low)} uK, 1 = +{round(high)} uK"
            ),
            "maxStopErrorOf255": round(colormap.legend_max_error(table, stops), 2),
            "source": config.COLORMAP_SOURCE,
        },
        "smoothingFwhmArcmin": config.SMOOTHING_FWHM_ARCMIN,
        "smoothing": {
            "kernel": "Gaussian in harmonic space: healpy.smoothing, ring weights, iter = 3, lmax = 3 NSIDE - 1",
            "nativeBeamFwhmArcmin": None if native is None else round(native, 2),
            "effectiveFwhmArcmin": None if native is None else round(math.hypot(native, config.SMOOTHING_FWHM_ARCMIN), 2),
        },
        "resampling": "bilinear HEALPix interpolation (healpy.get_interp_val) at every texel centre",
        "mipmaps": (
            f"{encoded['files']['4096']['levels']} levels, {config.WIDTH}x{config.HEIGHT} down to 1x1, made offline "
            "with a 2x2 box filter in linear light; cmb-2048 holds levels 1 to the end of the same chain"
        ),
        "colorSpace": "srgb",
        "encoding": {
            "codec": config.KTX_CODEC,
            "tool": encoded["tool"],
            "args": encoded["args"],
            "files": encoded["files"],
        },
        "credit": config.CREDIT,
        "source": {
            "file": config.FITS_NAME,
            "sha256": config.FITS_SHA256,
            "bytes": config.FITS_BYTES,
            "release": config.RELEASE,
            "method": source["method"],
            "url": config.FITS_URL,
            "plaUrl": config.FITS_PLA_URL,
            "hdu": 1,
            "ordering": source["ordering"],
            "nside": source["nside"],
            "coordsys": source["coordsys"],
            "unitInFile": source["unit_in_file"],
            "conversion": "K_CMB x 1e6 = uK_CMB",
            "monopoleUk": round(stats["rawMap"]["fittedMonopoleUk"], 3),
            "residualDipoleUk": round(stats["rawMap"]["fittedDipoleAmplitudeUk"], 3),
        },
        "verification": {
            "convention": stats["checks"]["conventionCheck"],
            "coldSpotMeanUk": stats["checks"]["coldSpot"],
            "galacticPlaneStdUk": stats["checks"]["galacticPlane"],
            "planck2018Figure": previews.get("paperComparison"),
            "decoded": previews.get("decoded"),
        },
        "software": _software(),
    }
