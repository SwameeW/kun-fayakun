"""Writes public/assets/places/places.json: the world's notable populated places, for the explorer's
place search ("find a place") and its field notes (where the Sun is overhead, where dawn is breaking).

Source: Natural Earth 1:50m populated places (ne_50m_populated_places_simple), version 5.1.2, public
domain, pinned by sha256. Kept per place: name, latitude, longitude (degrees, as Natural Earth gives
them) and the larger population estimate (pop_max), sorted by population so the largest come first.
Nothing is typed by hand.

No country is kept. The data assigns disputed places to one country or another, and saying who governs
a city is a position this site does not take; the coordinates tell places of the same name apart.

Usage: python3 -I scripts/places/build.py   (network on the first run; the download is cached in .cache/places)
"""

from __future__ import annotations

import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / ".cache" / "places"
OUT = ROOT / "public" / "assets" / "places" / "places.json"
URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_50m_populated_places_simple.geojson"
SHA256 = "8e70756b39fae9bcdc1e332bfc510c024c5edd3a13203ffd20092ee37b61d978"
SOURCE_ID = "natural-earth-5.1.2-places"


def fetch() -> bytes:
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / "ne_50m_populated_places_simple.geojson"
    if not path.exists():
        # curl, as the other builders do (Python's own TLS store fails on some machines).
        subprocess.run(["curl", "-sSfL", "--max-time", "120", "-o", str(path), URL], check=True)
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"{path.name}: sha256 {digest} is not the pinned {SHA256}")
    return data


def main() -> None:
    features = json.loads(fetch())["features"]
    places = []
    for f in features:
        p = f["properties"]
        name = (p.get("name") or "").strip()
        lat, lon = p.get("latitude"), p.get("longitude")
        if not name or not isinstance(lat, (int, float)) or not isinstance(lon, (int, float)):
            continue
        population = p.get("pop_max") if isinstance(p.get("pop_max"), int) else 0
        places.append([name, round(lat, 4), round(lon, 4), max(0, population)])
    places.sort(key=lambda r: (-r[3], r[0]))
    out = {
        "$comment": "Generated by scripts/places/build.py from Natural Earth (public domain). Do not edit by hand.",
        "source": {"id": SOURCE_ID, "url": URL, "sha256": SHA256},
        "fields": ["name", "lat", "lon", "population"],
        "places": places,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(places)} places")


if __name__ == "__main__":
    main()
